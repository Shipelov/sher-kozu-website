// ═══════════════════════════════════════════════════════════════════
// 5. Nutrition Profile Context
// ═══════════════════════════════════════════════════════════════════

function buildProfileContext(profile?: NutriProfile | null): string {
  if (!profile) return "";

  let section = `\n## Нутри-профиль пользователя\n`;

  if (profile.goals && (profile.goals as string[]).length > 0) {
    section += `- **Цели:** ${(profile.goals as string[]).join(", ")}\n`;
  }
  if (profile.allergies && (profile.allergies as string[]).length > 0) {
    section += `- **Аллергии:** ${(profile.allergies as string[]).join(", ")}\n`;
  }
  if (profile.restrictions && (profile.restrictions as string[]).length > 0) {
    section += `- **Ограничения:** ${(profile.restrictions as string[]).join(", ")}\n`;
  }
  if (profile.familyMembers && (profile.familyMembers as any[]).length > 0) {
    section += `- **Семья:** ${(profile.familyMembers as any[]).map((m: any) => `${m.name}${m.age ? ` (${m.age} лет)` : ""}`).join(", ")}\n`;
  }
  if (profile.preferredProducts && (profile.preferredProducts as string[]).length > 0) {
    section += `- **Предпочитаемые продукты:** ${(profile.preferredProducts as string[]).join(", ")}\n`;
  }

  return section;
}

// ═══════════════════════════════════════════════════════════════════
// 6. RAG Context (retrieved knowledge entries)
// ═══════════════════════════════════════════════════════════════════

function buildRAGContext(entries: NutriKnowledgeEntry[]): string {
  if (!entries.length) return "";

  let section = `\n## Релевантные знания из базы (используй для ответа)\n`;

  for (const entry of entries.slice(0, 8)) {
    section += `\n### ${entry.title}\n`;
    section += `${entry.content}\n`;
    if (entry.sourceName) {
      section += `_Источник: ${entry.sourceName}_\n`;
    }
  }

  return section;
}

